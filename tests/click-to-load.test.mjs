// Teste v2.1.0: modul opțional „clic pentru încărcare” (nicio cerere către Meta până la confirmare).
import {createRequire} from 'node:module';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const require = createRequire(process.env.PW_ROOT || import.meta.url);
const {chromium} = require('playwright');
const here = path.dirname(fileURLToPath(import.meta.url));
const FILE = 'file://' + path.resolve(here, '..', 'index.html');
let ok = 0, bad = 0;
const t = (n, c, x) => { if (c) { ok++; console.log('  ok  ' + n); } else { bad++; console.log('  FAIL ' + n + (x ? ' :: ' + JSON.stringify(x) : '')); } };
const b = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox']});
const ctx = await b.newContext({locale: 'ro-RO'});
const reqs = [];
await ctx.route(/^https?:/, (r) => { reqs.push(r.request().url()); r.fulfill({status: 200, contentType: 'text/html', body: '<!doctype html><title>stub</title>'}); });
const p = await ctx.newPage(); const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => { if (/Content Security Policy|Refused to/i.test(m.text())) errs.push(m.text()); });
await p.goto(FILE); await p.waitForTimeout(600);
const U = 'https://www.facebook.com/exemplu';
const fb = () => reqs.filter((u) => /facebook\.com/.test(u));
t('mod oprit implicit (comportament neschimbat)', await p.evaluate(() => !document.getElementById('c2lChk').checked));
await p.fill('#urlInput', U); await p.click('button[type=submit]'); await p.waitForTimeout(500);
t('fără bifă: iframe încărcat direct', await p.locator('#embedStage iframe').count() === 1 && fb().length >= 1, fb());
await p.click('#clearBtn'); reqs.length = 0;
await p.check('#c2lChk');
await p.fill('#urlInput', U); await p.click('button[type=submit]'); await p.waitForTimeout(600);
t('cu bifă: substituent, fără iframe', await p.locator('#embedStage iframe').count() === 0 && await p.locator('#c2lGo').count() === 1);
t('cu bifă: nicio cerere către facebook.com', fb().length === 0, fb());
t('substituentul spune ce primește Meta', /IP/.test(await p.textContent('.embed-gate')));
await p.selectOption('#langSelect', 'de'); await p.waitForTimeout(200);
t('schimbarea limbii nu contactează Meta și retraduce', fb().length === 0 && await p.textContent('#c2lGo') === 'Von Meta laden');
await p.click('#c2lGo'); await p.waitForTimeout(500);
t('după clic: iframe creat și cerere către facebook.com', await p.locator('#embedStage iframe').count() === 1 && fb().length >= 1, fb());
t('fără pageerror/CSP', errs.length === 0, errs);
await b.close();
console.log('\n' + ok + ' ok, ' + bad + ' eșuate');
process.exit(bad ? 1 : 0);
